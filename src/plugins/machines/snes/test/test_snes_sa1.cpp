// The SA-1 with a small hand-built cartridge: the S-CPU starts the SA-1,
// which multiplies, writes BW-RAM (plain and as a 4-bit bitmap), sends a
// message, and signals through I-RAM.

#include "test_harness.h"
#include "plugins/machines/snes/main/machine_snes.h"
#include "libcore/main/machine_desc.h"
#include "libmem/main/ibus.h"
#include <string>
#include <vector>

namespace {

std::vector<uint8_t> sa1Cart() {
    std::vector<uint8_t> img(0x10000, 0);
    const char* title = "MMSIM SA1            ";
    for (int i = 0; i < 21; ++i) img[0x7FC0 + i] = (uint8_t)title[i];
    img[0x7FD5] = 0x23; img[0x7FD6] = 0x34; img[0x7FD7] = 0x06; img[0x7FD8] = 0x03;   // SA-1, 8 KB BW-RAM
    img[0x7FDC] = 0xFF; img[0x7FDD] = 0xFF;
    img[0x7FFC] = 0x00; img[0x7FFD] = 0x80;
    const uint8_t cpu[] = {
        0x78, 0x18, 0xFB, 0xE2, 0x30,                       // SEI CLC XCE SEP #$30
        0xA9, 0x00, 0x8D, 0x03, 0x22, 0xA9, 0x90, 0x8D, 0x04, 0x22,   // SA-1 reset vector $9000
        0x9C, 0x00, 0x22,                                   // CCNT = 0: the SA-1 runs
        0xAD, 0x00, 0x30, 0xC9, 0x42, 0xD0, 0xF9,           // wait for I-RAM $3000 = $42
        0xAD, 0x01, 0x30, 0x8D, 0x00, 0x00,                 // the product
        0xAD, 0x02, 0x30, 0x8D, 0x01, 0x00,
        0xAD, 0x00, 0x23, 0x8D, 0x02, 0x00,                 // SFR
        0xAD, 0x05, 0x60, 0x8D, 0x03, 0x00,                 // BW-RAM $0005
        0xAD, 0x00, 0x60, 0x8D, 0x04, 0x00,                 // BW-RAM $0000 (the bitmap write)
        0x80, 0xFE,
    };
    std::copy(cpu, cpu + sizeof cpu, img.begin());
    const uint8_t sa1[] = {
        0x78, 0x18, 0xFB, 0xE2, 0x30,
        0xA9, 0xFF, 0x8D, 0x2A, 0x22,                       // CIWP: I-RAM writable
        0xA9, 0x80, 0x8D, 0x27, 0x22,                       // CBWE: BW-RAM writable
        0x9C, 0x50, 0x22,                                   // MCNT: multiply
        0xA9, 0x03, 0x8D, 0x51, 0x22, 0xA9, 0x01, 0x8D, 0x52, 0x22,   // MA = $0103
        0xA9, 0x07, 0x8D, 0x53, 0x22, 0x9C, 0x54, 0x22,     // MB = $0007: go
        0xEA, 0xEA, 0xEA,
        0xAD, 0x06, 0x23, 0x8D, 0x01, 0x30,                 // the result to I-RAM
        0xAD, 0x07, 0x23, 0x8D, 0x02, 0x30,
        0xA9, 0xAB, 0x8F, 0x05, 0x00, 0x40,                 // BW-RAM $40:0005
        0x9C, 0x3F, 0x22,                                   // BBF: 4 bits a pixel
        0xA9, 0x0C, 0x8F, 0x01, 0x00, 0x60,                 // bitmap pixel 1 = $C: byte 0's high nibble
        0xA9, 0x85, 0x8D, 0x09, 0x22,                       // SCNT: message 5, IRQ to the S-CPU
        0xA9, 0x42, 0x8D, 0x00, 0x30,                       // done
        0x80, 0xFE,
    };
    std::copy(sa1, sa1 + sizeof sa1, img.begin() + 0x1000);
    return img;
}

}  // namespace

TEST_CASE(snes_sa1_program) {
    std::string err;
    MachineDescriptor* m = snes::create(false, &err);
    ASSERT(snes::insertCartridge(m, sa1Cart(), "sa1.sfc", err));
    EXPECT_EQ(snes::cartridgeInfo(m), std::string("sa1.sfc (MMSIM SA1, LoROM, 64K ROM, 8K RAM, SA-1)"));
    uint64_t t = 0;
    while (t < 400000) t += (uint64_t)m->schedulerStep(*m);
    IBus* bus = m->buses[0].bus;
    EXPECT_EQ(bus->peek8(0x000000), 0x15);                  // $0103 * 7 = $0715
    EXPECT_EQ(bus->peek8(0x000001), 0x07);
    EXPECT_EQ(bus->peek8(0x000002), 0x85);                  // message 5, IRQ requested
    EXPECT_EQ(bus->peek8(0x000003), 0xAB);
    EXPECT_EQ(bus->peek8(0x000004), 0xC0);
    delete m;
}

// DMA from ROM to I-RAM, signed division, and the variable-length bit reader
TEST_CASE(snes_sa1_dma_divide_bits) {
    std::vector<uint8_t> img = sa1Cart();
    const uint8_t sa1[] = {
        0x78, 0x18, 0xFB, 0xE2, 0x30,
        0xA9, 0xFF, 0x8D, 0x2A, 0x22,                       // CIWP
        // DMA: ROM $00:A000 -> I-RAM $0100, 4 bytes
        0xA9, 0x80, 0x8D, 0x30, 0x22,                       // DCNT: on, ROM -> I-RAM
        0x9C, 0x32, 0x22, 0xA9, 0xA0, 0x8D, 0x33, 0x22, 0x9C, 0x34, 0x22,
        0xA9, 0x04, 0x8D, 0x38, 0x22, 0x9C, 0x39, 0x22,
        0x9C, 0x35, 0x22, 0xA9, 0x01, 0x8D, 0x36, 0x22,     // DDA = $0100: go
        // -7 / 2 = -4 remainder 1
        0xA9, 0x01, 0x8D, 0x50, 0x22,
        0xA9, 0xF9, 0x8D, 0x51, 0x22, 0xA9, 0xFF, 0x8D, 0x52, 0x22,
        0xA9, 0x02, 0x8D, 0x53, 0x22, 0x9C, 0x54, 0x22,
        0xEA, 0xEA, 0xEA,
        0xAD, 0x06, 0x23, 0x8D, 0x10, 0x30, 0xAD, 0x07, 0x23, 0x8D, 0x11, 0x30,
        0xAD, 0x08, 0x23, 0x8D, 0x12, 0x30,
        // Bits from $00:A004 (A5 3C FF), 4 at a time
        0xA9, 0x04, 0x8D, 0x59, 0x22, 0xA9, 0xA0, 0x8D, 0x5A, 0x22, 0x9C, 0x5B, 0x22,
        0xA9, 0x84, 0x8D, 0x58, 0x22,
        0xAD, 0x0C, 0x23, 0x8D, 0x20, 0x30,                 // $A5
        0xAD, 0x0D, 0x23, 0x8D, 0x21, 0x30,                 // $3C, then 4 bits on
        0xAD, 0x0C, 0x23, 0x8D, 0x22, 0x30,                 // $CA
        0xA9, 0x42, 0x8D, 0x00, 0x30,
        0x80, 0xFE,
    };
    std::fill(img.begin() + 0x1000, img.begin() + 0x1100, 0);
    std::copy(sa1, sa1 + sizeof sa1, img.begin() + 0x1000);
    const uint8_t data[] = {0x11, 0x22, 0x33, 0x44, 0xA5, 0x3C, 0xFF};
    std::copy(data, data + sizeof data, img.begin() + 0x2000);
    std::string err;
    MachineDescriptor* m = snes::create(false, &err);
    ASSERT(snes::insertCartridge(m, img, "sa1.sfc", err));
    uint64_t t = 0;
    while (t < 400000) t += (uint64_t)m->schedulerStep(*m);
    IBus* bus = m->buses[0].bus;
    EXPECT_EQ(bus->peek8(0x003000), 0x42);
    EXPECT_EQ(bus->peek8(0x003100), 0x11);
    EXPECT_EQ(bus->peek8(0x003103), 0x44);
    EXPECT_EQ(bus->peek8(0x003010), 0xFC);                  // quotient $FFFC
    EXPECT_EQ(bus->peek8(0x003011), 0xFF);
    EXPECT_EQ(bus->peek8(0x003012), 0x01);                  // remainder 1
    EXPECT_EQ(bus->peek8(0x003020), 0xA5);
    EXPECT_EQ(bus->peek8(0x003021), 0x3C);
    EXPECT_EQ(bus->peek8(0x003022), 0xCA);
    delete m;
}
