bool Gameboy::load(std::vector<uint8_t> rom, std::string& err) {
    if (rom.size() < 0x150) { err = "Game Boy ROM too small (" + std::to_string(rom.size()) + " bytes)"; return false; }
    if (rom.size() & 0x3FFF) rom.resize((rom.size() + 0x3FFF) & ~(size_t)0x3FFF, 0);   // whole 16 KB banks, as Mesen
    m_header = Header::parse(rom);
    auto cart = Cart::create(m_header, rom, err);
    if (!cart) return false;
    m_rom = std::move(rom);
    m_cart = std::move(cart);
    m_cart->attach(this);
    m_cartRam.assign(m_header.cartRamSize(), 0);
    return true;
}

void Gameboy::powerOn(SgbLink* sgb) {
    m_sgb = sgb;
    // Mesen's Init order: the timer, the APU, the cartridge, the memory map, the CPU, the PPU, DMA
    m_div = 0x06;                                        // Mesen's (boot_div-dmgABCmgb)
    m_timerBit = 1024;
    m_needReload = m_reloaded = m_timerOn = false;
    m_tima = m_tma = m_tac = 0;
    m_apuCycles = 0;
    m_apu.init();
    m_wram.assign(isCgb() ? 0x8000 : 0x2000, 0);
    std::memset(m_hram, 0, sizeof(m_hram));
    std::memset(m_reads, 0, sizeof(m_reads));
    std::memset(m_writes, 0, sizeof(m_writes));
    std::memset(m_readReg, 0, sizeof(m_readReg));
    std::memset(m_writeReg, 0, sizeof(m_writeReg));
    m_ie = m_if = 0;
    m_serialData = m_serialControl = m_serialBits = 0;
    m_serialOut.clear();
    m_joySelect = 0x30;
    m_highSpeed = m_speedSwitchRequest = false;
    m_frameSeqDelay = 0;
    m_wramBank = 1;
    m_hdmaSource = m_hdmaDest = 0;
    m_hdmaLength = 0;
    m_hdmaRunning = m_hdmaPending = m_hdmaTrigger = false;
    m_ff72 = m_ff73 = m_ff74 = m_ff75 = m_rp = 0;
    if (isCgb() && m_skipBootRom) m_bootRom.clear();
    else if (!m_bootRomOverride.empty()) m_bootRom = m_bootRomOverride;
    else if (m_model == Model::Sgb) m_bootRom.assign(SGB_BOOT, SGB_BOOT + 256);
    else if (m_model == Model::Sgb2) m_bootRom.assign(SGB2_BOOT, SGB2_BOOT + 256);
    else if (m_model == Model::Cgb) m_bootRom.assign(CGB_BOOT, CGB_BOOT + sizeof(CGB_BOOT));
    else m_bootRom.clear();
    m_bootRomOff = m_bootRom.empty();
    m_sgbBootRom = isSgb() && m_bootRomOverride.empty() && !m_bootRomOff;
    mapRegisters(0x8000, 0x9FFF, ACC_RW);
    mapRegisters(0xFE00, 0xFFFF, ACC_RW);
    if (m_cart) m_cart->initCart();
    refreshMappings();
    m_cpu.init();
    m_ppu.init();
    std::memset(m_ppu.vram(), 0, Ppu::VRAM_SIZE);
    std::memset(m_ppu.oam(), 0, 0xA0);
    m_dmaSource = 0xFF;
    m_dmaStartDelay = m_dmaDest = m_dmaCounter = m_dmaBuffer = 0;
    m_dmaRunning = false;
    if (m_bootRomOff) {
        if (isCgb()) cgbPostBootState();
        else postBootState();
    }
    m_cpu.powerOn();
}

/** Where the DMG boot ROM leaves things (Pan Docs' "Power Up Sequence"), for a start without one. */
void Gameboy::postBootState() {
    auto& s = m_cpu.state();
    s.a = 0x01; s.f = 0xB0; s.b = 0x00; s.c = 0x13; s.d = 0x00; s.e = 0xD8; s.h = 0x01; s.l = 0x4D;
    s.sp = 0xFFFE; s.pc = 0x0100;
    // The sound: the boot ROM's chime on square 1 (NR52 $F1)
    write(0xFF26, 0x80);
    write(0xFF11, 0x80);
    write(0xFF12, 0xF3);
    write(0xFF25, 0xF3);
    write(0xFF24, 0x77);
    write(0xFF13, 0xC1);
    write(0xFF14, 0x87);
    write(0xFF47, 0xFC);
    write(0xFF40, 0x91);
    m_serialControl = 0;                                 // SC reads $7E
    m_joySelect = 0x00;                                  // P1 reads $CF
    // The internal counter as the DMG boot ROM hands over: DIV $AB with its phase
    // that of boot_div-dmgABCmgb (DIV reads $AC 6 NOPs in), and the serial clock
    // (which Mesen runs off the clock counter, where it starts in step with the
    // counter) aligned with it as boot_sclk_align-dmgABCmgb measures
    m_div = 0xABCA;
    m_cpu.cycleRef() = m_div & 0x1FF;
    m_tac = 0;                                           // TAC reads $F8
    m_if = 0x01;
}

/**
 * Where the CGB boot ROM leaves things (Pan Docs' "Power Up Sequence", CGB
 * column), for a start without one (Mesen always runs one). A DMG cartridge
 * gets the compatibility mode and the colours of a title the boot ROM has no
 * palette for; a CGB one white background palettes.
 */
void Gameboy::cgbPostBootState() {
    const bool cgbCart = m_rom.size() > 0x143 && (m_rom[0x143] & 0x80);
    auto& s = m_cpu.state();
    s.a = 0x11; s.f = 0x80; s.b = 0x00; s.c = 0x00;
    s.d = cgbCart ? 0xFF : 0x00; s.e = cgbCart ? 0x56 : 0x08;
    s.h = 0x00; s.l = cgbCart ? 0x0D : 0x7C;
    s.sp = 0xFFFE; s.pc = 0x0100;
    write(0xFF26, 0x80);
    write(0xFF11, 0x80);
    write(0xFF12, 0xF3);
    write(0xFF25, 0xF3);
    write(0xFF24, 0x77);
    write(0xFF13, 0xC1);
    write(0xFF14, 0x87);
    write(0xFF47, 0xFC);
    if (cgbCart) {
        for (int i = 0; i < 32; ++i) m_ppu.bgPalettes()[i] = 0x7FFF;
    } else {
        m_ppu.setCgbEnabled(false);                      // KEY0 $04, as the boot ROM writes
        for (int i = 0; i < 4; ++i) {
            m_ppu.bgPalettes()[i] = CGB_COMPAT_BG[i];
            m_ppu.objPalettes()[i] = m_ppu.objPalettes()[i + 4] = CGB_COMPAT_OBJ[i];
        }
    }
    write(0xFF40, 0x91);
    m_serialControl = 0;
    m_joySelect = 0x00;
    m_div = 0xABCA;
    m_cpu.cycleRef() = m_div & 0x1FF;
    m_tac = 0;
    m_if = 0x01;
    refreshMappings();
}

/**
 * The SGB boot ROM's hand-off. Nintendo's takes one machine cycle less for each 1
 * bit of the cartridge header it sends ($0104-$014F), so DIV's value and phase at
 * $0100 depend on the header (Mooneye's boot_div-S and boot_div2-S differ only in
 * the global checksum, by 4 bits and 4 NOPs); SameBoy's takes the same time for
 * either bit. It ends in step with Nintendo's for a header of 270 1 bits
 * (boot_div2-S's), and DIV is moved by the difference.
 */
void Gameboy::sgbBootDuration() {
    int ones = 0;
    for (int a = 0x104; a < 0x150 && a < (int)m_rom.size(); ++a) ones += __builtin_popcount(m_rom[a]);
    m_div = (uint16_t)(m_div + 4 * (270 - ones));
}

void Gameboy::runTo(uint64_t cycle) {
    if (!m_cart) return;
    while (m_cpu.cycles() < cycle) m_cpu.exec();
}

void Gameboy::runFrame() {
    if (!m_cart) return;
    const uint32_t f = m_ppu.frameCount();
    while (f == m_ppu.frameCount()) m_cpu.exec();
    m_apu.run();
}

