std::vector<uint8_t>* Gameboy::memory(Mem type) {
    switch (type) {
    case Mem::Rom: return &m_rom;
    case Mem::WorkRam: return &m_wram;
    case Mem::CartRam: return &m_cartRam;
    case Mem::BootRom: return &m_bootRom;
    default: return nullptr;
    }
}

void Gameboy::map(uint16_t start, uint16_t end, Mem type, uint32_t offset, bool readOnly) {
    auto* mem = memory(type);
    if (!mem || mem->empty()) { unmap(start, end); return; }
    const uint32_t size = (uint32_t)mem->size();
    offset %= size;
    for (int i = start; i < end; i += 0x100) {
        uint8_t* p = mem->data() + offset;
        m_reads[i >> 8] = p;
        m_writes[i >> 8] = readOnly ? nullptr : p;
        offset += 0x100;
        if (offset >= size) offset = 0;
    }
}

void Gameboy::unmap(uint16_t start, uint16_t end) {
    for (int i = start; i < end; i += 0x100) m_reads[i >> 8] = m_writes[i >> 8] = nullptr;
}

void Gameboy::mapRegisters(uint16_t start, uint16_t end, uint8_t access) {
    for (int i = start; i < end; i += 0x100) {
        m_readReg[i >> 8] = (access & ACC_READ) != 0;
        m_writeReg[i >> 8] = (access & ACC_WRITE) != 0;
    }
}

uint8_t Gameboy::wramBank() const {
    return m_ppu.cgbEnabled() ? std::max<uint8_t>(1, m_wramBank) : 1;   // bank 0 selects 1
}

void Gameboy::refreshMappings() {
    const uint32_t bank = wramBank() * 0x1000u;
    map(0xC000, 0xCFFF, Mem::WorkRam, 0, false);
    map(0xD000, 0xDFFF, Mem::WorkRam, bank, false);
    map(0xE000, 0xEFFF, Mem::WorkRam, 0, false);
    map(0xF000, 0xFFFF, Mem::WorkRam, bank, false);
    if (m_cart) m_cart->refreshMappings();
    if (!m_bootRomOff) {
        map(0x0000, 0x00FF, Mem::BootRom, 0, true);
        if (m_bootRom.size() >= 0x900) map(0x0200, 0x08FF, Mem::BootRom, 0x200, true);   // the CGB's: the header between
    }
}

// ---------------------------------------------------------------------------
// Time (Mesen's GbMemoryManager::Exec / ExecMasterCycle)
// ---------------------------------------------------------------------------

void Gameboy::timerDmaSerial() {
    m_apuCycles += m_highSpeed ? 1 : 2;                   // the APU keeps the normal speed's time
    timerExec();
    if ((m_cpu.cycles() & 3) == 0) dmaExec();
    if (m_serialBits && (m_cpu.cycles() & 0x1FF) == 0) {
        // The internal clock shifts a bit out (and a 1 in: nothing is connected)
        m_serialData = (uint8_t)(m_serialData << 1 | 1);
        if (--m_serialBits == 0) {
            m_serialControl &= 0x7F;
            requestIrq(IRQ_SERIAL);
        }
    }
}

void Gameboy::execMasterCycle() {
    uint64_t& c = m_cpu.cycleRef();
    ++c;
    if (c & 1) timerDmaSerial();
    m_ppu.exec(true);
}

void Gameboy::exec() {
    m_cpu.cycleRef() += 2;
    timerDmaSerial();
    m_ppu.exec(false);
}

uint8_t Gameboy::execSamplingIrq() {
    m_cpu.cycleRef() += 2;
    timerDmaSerial();
    m_ppu.exec(true);
    const uint8_t irq = pendingIrq();
    m_ppu.exec(true);
    return irq;
}

// ---------------------------------------------------------------------------
// Reads and writes
// ---------------------------------------------------------------------------

template <OamCorruption C> uint8_t Gameboy::read(uint16_t addr) {
    if (m_dmaRunning && dmaConflict(addr)) addr = dmaReadAddress();   // the CPU sees what DMA reads
    if (m_readReg[addr >> 8]) {
        m_ppu.oamCorruption<C>(addr);
        return readRegister(addr);
    }
    if (m_reads[addr >> 8]) return m_reads[addr >> 8][addr & 0xFF];
    return 0;
}

void Gameboy::write(uint16_t addr, uint8_t v) {
    if (m_dmaRunning && dmaConflict(addr)) return;
    if (m_writeReg[addr >> 8]) {
        m_ppu.oamCorruption<OamCorruption::Write>(addr);
        writeRegister(addr, v);
    } else if (m_writes[addr >> 8]) {
        m_writes[addr >> 8][addr & 0xFF] = v;
    }
}

void Gameboy::cpuWrite(uint16_t addr, uint8_t v) {
    if (addr == 0xFF40 && isCgb()) {
        // The CGB's fetch glitch: clearing LCDC bit 4 as the background fetcher reads a
        // tile's data gives it the tile's index instead (cgb-acid-hell)
        exec();
        exec();
        if ((m_ppu.control() & 0x10) && !(v & 0x10)) m_ppu.setTileFetchGlitch();
        write(addr, v);
        return;
    }
    if (addr == 0xFF47) {
        // BGP takes effect a little earlier than other writes (ppu_scanline_bgp, m3_bgp_change)
        execMasterCycle();
        execMasterCycle();
        execMasterCycle();
        write(addr, v);
        execMasterCycle();
        return;
    }
    exec();
    exec();
    write(addr, v);
}

uint8_t Gameboy::peek(uint16_t addr) {
    if (m_readReg[addr >> 8]) {
        if (isCgb() && (addr == 0xFF76 || addr == 0xFF77)) return m_apu.pcm(addr);   // without running the APU
        if (addr >= 0xFF40) return readRegister(addr);
        if (addr >= 0xFE00 && addr < 0xFEA0) return m_ppu.readOam((uint8_t)addr);
        if (addr >= 0xFF10 && addr < 0xFF40) return m_apu.peek(addr);
        if (addr >= 0x8000 && addr < 0xA000) return m_ppu.readVram(addr);
        if (addr >= 0xFF00 && addr < 0xFF10 && addr != 0xFF00) return readRegister(addr);
        if (addr == 0xFF00) return readJoypad();
        return 0xFF;
    }
    return m_reads[addr >> 8] ? m_reads[addr >> 8][addr & 0xFF] : 0;
}

void Gameboy::poke(uint16_t addr, uint8_t v) {
    if (!m_writeReg[addr >> 8] && m_writes[addr >> 8]) m_writes[addr >> 8][addr & 0xFF] = v;
}

uint8_t Gameboy::pendingIrq() const {
    const uint8_t r = m_if & m_ie & 0x1F;
    if (!r) return 0;
    return (uint8_t)(r & -r);     // the lowest bit: VBlank first
}

uint8_t Gameboy::readRegister(uint16_t addr) {
    if (addr >= 0xFF00) {
        if (addr == 0xFFFF) return m_ie;
        if (addr == 0xFF46) return m_dmaSource;
        if (addr >= 0xFF80) return m_hram[addr & 0x7F];
        if (addr >= 0xFF4C) {
            if (!isCgb()) return 0xFF;                   // nothing
            const bool cgbMode = m_ppu.cgbEnabled();
            switch (addr) {
            case 0xFF4D: return cgbMode ? (uint8_t)((m_highSpeed ? 0x80 : 0) | (m_speedSwitchRequest ? 0x01 : 0) | 0x7E) : 0xFF;
            case 0xFF55: return cgbMode ? (uint8_t)(m_hdmaLength | (m_hdmaRunning ? 0 : 0x80)) : 0xFF;
            case 0xFF56: return (uint8_t)(m_rp | 0x3E);      // the infrared port: nothing received
            case 0xFF4F: case 0xFF68: case 0xFF69: case 0xFF6A: case 0xFF6B: return m_ppu.readCgb(addr);
            case 0xFF70: return cgbMode ? (uint8_t)(m_wramBank | 0xF8) : 0xFF;
            case 0xFF72: return m_ff72;
            case 0xFF73: return m_ff73;
            case 0xFF74: return cgbMode ? m_ff74 : 0xFF;
            case 0xFF75: return (uint8_t)(m_ff75 | 0x8F);
            case 0xFF76: case 0xFF77: m_apu.run(); return m_apu.pcm(addr);
            default: return 0xFF;
            }
        }
        if (addr >= 0xFF40) return m_ppu.read(addr);
        if (addr >= 0xFF10) return m_apu.read(addr);
        switch (addr) {
        case 0xFF00: return readJoypad();
        case 0xFF01: return m_serialData;
        case 0xFF02: return (uint8_t)(m_serialControl | (m_ppu.cgbEnabled() ? 0x7C : 0x7E));
        case 0xFF04: case 0xFF05: case 0xFF06: case 0xFF07: return timerRead(addr);
        case 0xFF0F: return (uint8_t)(m_if | 0xE0);
        default: return 0xFF;
        }
    }
    if (addr >= 0xFE00) return m_ppu.readOam((uint8_t)addr);
    if (addr >= 0x8000 && addr < 0xA000) return m_ppu.readVram(addr);
    return m_cart ? m_cart->readRegister(addr) : 0xFF;
}

void Gameboy::writeRegister(uint16_t addr, uint8_t v) {
    if (addr >= 0xFF00) {
        if (addr == 0xFFFF) { m_ie = v; return; }
        if (addr == 0xFF46) { m_dmaStartDelay = 1; m_dmaSource = v; return; }
        if (addr >= 0xFF80) { m_hram[addr & 0x7F] = v; return; }
        if (addr >= 0xFF4C) {
            if (addr == 0xFF50) {
                if ((v & 1) && !m_bootRomOff) {
                    m_bootRomOff = true;
                    refreshMappings();
                    if (m_sgbBootRom) sgbBootDuration();
                }
                return;
            }
            if (!isCgb()) return;
            const bool cgbMode = m_ppu.cgbEnabled();
            switch (addr) {
            case 0xFF4D: if (cgbMode) m_speedSwitchRequest = (v & 1) != 0; break;     // KEY1: STOP switches
            case 0xFF51: case 0xFF52: case 0xFF53: case 0xFF54: case 0xFF55: if (cgbMode) hdmaWrite(addr, v); break;
            case 0xFF56: if (cgbMode) m_rp = v & 0xC1; break;
            case 0xFF4C: if (!m_bootRomOff) m_ppu.writeCgb(addr, v); break;     // KEY0: the boot ROM's only
            case 0xFF4F: case 0xFF68: case 0xFF69: case 0xFF6A: case 0xFF6B: m_ppu.writeCgb(addr, v); break;
            case 0xFF70:
                if (cgbMode) {
                    m_wramBank = v & 0x07;
                    refreshMappings();
                }
                break;
            case 0xFF72: m_ff72 = v; break;
            case 0xFF73: m_ff73 = v; break;
            case 0xFF74: if (cgbMode) m_ff74 = v; break;
            case 0xFF75: m_ff75 = v; break;
            }
            return;
        }
        if (addr >= 0xFF40) { m_ppu.write(addr, v); return; }
        if (addr >= 0xFF10) { m_apu.write(addr, v); return; }
        switch (addr) {
        case 0xFF00:
            // Changing the select lines can raise the joypad interrupt (Double Dragon 3, as Mesen)
            inputChange([&]() { m_joySelect = v & 0x30; });
            if (m_sgb) m_sgb->joypadWrite(m_joySelect);
            break;
        case 0xFF01: m_serialData = v; break;
        case 0xFF02:
            // The CGB mode's fast clock bit, kept (not run faster, as Mesen); in DMG mode it is unused (Mesen
            // keeps it there too: unused_hwio-C)
            m_serialControl = v & (m_ppu.cgbEnabled() ? 0x83 : 0x81);
            if ((m_serialControl & 0x80) && (m_serialControl & 0x01)) {
                m_serialBits = 8;
                m_serialOut += (char)m_serialData;       // what's sent (Blargg's tests print this way)
            } else {
                m_serialBits = 0;
            }
            break;
        case 0xFF04: case 0xFF05: case 0xFF06: case 0xFF07: timerWrite(addr, v); break;
        case 0xFF0F: m_if = v & 0x1F; break;
        }
        return;
    }
    if (addr >= 0xFE00) { m_ppu.writeOam((uint8_t)addr, v, false); return; }
    if (addr >= 0x8000 && addr < 0xA000) { m_ppu.writeVram(addr, v); return; }
    if (m_cart) m_cart->writeRegister(addr, v);
}

// ---------------------------------------------------------------------------
// The joypad (Mesen's GbControlManager)
// ---------------------------------------------------------------------------

uint8_t Gameboy::readJoypad() const {
    uint8_t r = 0x0F;
    const uint8_t sel = m_joySelect;
    if (m_sgb) {
        if ((sel & 0x30) == 0x30) r = m_sgb->joypadId();
        else {
            if (!(sel & 0x20)) r &= m_sgb->joypadButtons() >> 4;
            if (!(sel & 0x10)) r &= m_sgb->joypadButtons() & 0x0F;
        }
    } else {
        if (!(sel & 0x20)) r &= (uint8_t)~(m_buttons >> 4);
        if (!(sel & 0x10)) r &= (uint8_t)~(m_buttons & 0x0F);
    }
    return (uint8_t)((r & 0x0F) | (sel & 0x30) | 0xC0);
}

// ---------------------------------------------------------------------------
// The timer (Mesen's GbTimer)
// ---------------------------------------------------------------------------

void Gameboy::timerExec() {
    if (m_frameSeqDelay && --m_frameSeqDelay == 0) {
        if (m_frameSeqDelayedRise) m_apu.frameSequencerRise();
        else m_apu.clockFrameSequencer();
    }
    if ((m_div & 3) == 2) {
        m_reloaded = false;
        if (m_needReload) reloadTimer();
    }
    setDivider((uint16_t)(m_div + 2), true);
}

void Gameboy::reloadTimer() {
    m_tima = m_tma;
    requestIrq(IRQ_TIMER);
    m_needReload = false;
    m_reloaded = true;
}

void Gameboy::setDivider(uint16_t v, bool counting) {
    if (m_timerOn && !(v & m_timerBit) && (m_div & m_timerBit)) {
        if (++m_tima == 0) m_needReload = true;
    }
    const uint16_t frameSeqBit = m_highSpeed ? 0x2000 : 0x1000;
    const bool fall = !(v & frameSeqBit) && (m_div & frameSeqBit), rise = (v & frameSeqBit) && !(m_div & frameSeqBit);
    if (counting && (fall || rise) && m_apu.speedSwitchDelay()) {
        // Counted a machine cycle late (half of one in normal speed) after the speed switch
        // that delays it (AGE's m_current_ds_delay: spsw-ch2-lc-delay)
        m_frameSeqDelay = m_highSpeed ? 2 : 1;
        m_frameSeqDelayedRise = rise;
    } else if (fall) {
        m_apu.clockFrameSequencer();
    } else if (rise) {
        m_apu.frameSequencerRise();
    }
    m_div = v;
}

void Gameboy::resetDivider(bool duringStop) {
    if (duringStop) {
        // STOP's DIV reset doesn't see a bit that rose in this machine cycle fall (AGE's speed
        // change glitch): TIMA doesn't tick, but at 262 kHz (CGB E: spsw-tima, spsw-interrupts),
        // nor does the frame sequencer step
        auto justRose = [this](uint16_t bit) {
            const unsigned low = m_div & (2u * bit - 1);
            return low >= bit && low < bit + 4u;
        };
        if (m_timerOn && m_timerBit != (1 << 3) && justRose(m_timerBit)) m_div &= (uint16_t)~m_timerBit;
        const uint16_t frameSeqBit = m_highSpeed ? 0x2000 : 0x1000;
        if (justRose(frameSeqBit)) m_div &= (uint16_t)~frameSeqBit;
    }
    setDivider(0, false);
}

uint8_t Gameboy::timerRead(uint16_t addr) const {
    switch (addr) {
    case 0xFF04: return (uint8_t)(m_div >> 8);
    case 0xFF05: return m_tima;
    case 0xFF06: return m_tma;
    default: return (uint8_t)(m_tac | 0xF8);
    }
}

void Gameboy::timerWrite(uint16_t addr, uint8_t v) {
    switch (addr) {
    case 0xFF04: setDivider(0, false); break;
    case 0xFF05:
        if (m_needReload) m_needReload = false;           // a write cancels the reload and its interrupt
        if (!m_reloaded) m_tima = v;                      // ignored on the reload's cycle
        break;
    case 0xFF06:
        m_tma = v;
        if (m_reloaded) m_tima = v;
        break;
    case 0xFF07: {
        m_tac = v & 0x07;
        const bool on = (v & 0x04) != 0;
        static const uint16_t bits[4] = {1 << 9, 1 << 3, 1 << 5, 1 << 7};
        const uint16_t bit = bits[v & 3];
        if (m_timerOn) {
            // Changing TAC can tick TIMA (the falling edge of the multiplexer's output)
            const bool tick = on ? ((m_div & m_timerBit) && !(m_div & bit)) : (m_div & m_timerBit) != 0;
            if (tick && ++m_tima == 0) reloadTimer();
        }
        m_timerOn = on;
        m_timerBit = bit;
        break;
    }
    }
}

// ---------------------------------------------------------------------------
// OAM DMA (Mesen's GbDmaController)
// ---------------------------------------------------------------------------

void Gameboy::dmaExec() {
    if (m_cpu.halted()) return;                           // paused while the CPU is halted
    const bool wasRunning = m_dmaCounter > 0;
    if (wasRunning) {
        if (m_dmaCounter <= 160) m_ppu.writeOam((uint8_t)(160 - m_dmaCounter), m_dmaBuffer, true);
        --m_dmaCounter;
        m_dmaRunning = m_dmaCounter > 0;
        if (m_dmaRunning) m_dmaBuffer = dmaRead(dmaReadAddress());
    }
    if (m_dmaStartDelay > 0 && --m_dmaStartDelay == 0) {
        m_dmaDest = m_dmaSource;
        m_dmaCounter = 161;
        m_dmaRunning = wasRunning;
    }
}

bool Gameboy::dmaConflict(uint16_t addr) const {
    const uint8_t src = m_dmaSource;
    if (isCgb()) {
        // The CGB's work RAM has a bus of its own
        return (src < 0x80 && addr < 0x8000) || (src >= 0x80 && src <= 0x9F && addr >= 0x8000 && addr <= 0x9FFF) ||
               (src >= 0xA0 && src <= 0xFD && addr >= 0xA000 && addr <= 0xFDFF);
    }
    return ((src < 0x80 || (src >= 0xA0 && src <= 0xFD)) && (addr < 0x8000 || (addr >= 0xA000 && addr <= 0xFDFF))) ||
           (src >= 0x80 && src <= 0x9F && addr >= 0x8000 && addr <= 0x9FFF);
}

uint8_t Gameboy::dmaRead(uint16_t addr) {
    if (m_reads[addr >> 8]) return m_reads[addr >> 8][addr & 0xFF];
    if (addr >= 0x8000 && addr <= 0x9FFF) return m_ppu.readVram(addr);
    return 0;
}

// ---------------------------------------------------------------------------
// The CGB's HDMA (Mesen's GbDmaController)
// ---------------------------------------------------------------------------

void Gameboy::hdmaWrite(uint16_t addr, uint8_t v) {
    switch (addr) {
    case 0xFF51: m_hdmaSource = (uint16_t)((m_hdmaSource & 0xFF) | (v << 8)); break;
    case 0xFF52: m_hdmaSource = (uint16_t)((m_hdmaSource & 0xFF00) | (v & 0xF0)); break;
    case 0xFF53: m_hdmaDest = (uint16_t)((m_hdmaDest & 0xFF) | (v << 8)); break;
    case 0xFF54: m_hdmaDest = (uint16_t)((m_hdmaDest & 0xFF00) | (v & 0xF0)); break;
    case 0xFF55:
        m_hdmaLength = v & 0x7F;
        if (!(v & 0x80)) {
            if (m_hdmaRunning) {
                // Bit 7 clear during HDMA stops it (HDMA5 then reads $80 | the length)
                m_hdmaRunning = m_hdmaPending = m_hdmaTrigger = false;
            } else {
                // General DMA: 4 clocks to set up, then every block with the CPU stopped
                exec();
                exec();
                do hdmaBlock(); while (m_hdmaLength != 0x7F);
            }
        } else {
            // HBlank DMA: a block now if in HBlank (or with the LCD off), then one each HBlank
            m_hdmaRunning = true;
            processHdma();
        }
        break;
    }
}

void Gameboy::processHdma() {
    const bool trigger = m_hdmaRunning && m_ppu.mode() == PpuMode::HBlank;
    m_hdmaPending |= trigger && !m_hdmaTrigger;
    m_hdmaTrigger = trigger;
    if (m_hdmaPending && !m_cpu.halted()) {
        exec();                                           // 4 clocks to set up
        exec();
        hdmaBlock();
        m_hdmaPending = false;
    }
}

void Gameboy::hdmaBlock() {
    // 16 bytes, 2 clocks each (4 in double speed: the same time); from VRAM or $E000 up they read $FF
    const bool invalidSource = (m_hdmaSource >= 0x8000 && m_hdmaSource <= 0x9FFF) || m_hdmaSource >= 0xE000;
    for (int i = 0; i < 16; ++i) {
        const uint16_t dst = (uint16_t)(0x8000 | ((m_hdmaDest + i) & 0x1FFF));
        exec();
        uint8_t v = read<OamCorruption::Read>((uint16_t)(m_hdmaSource + i));
        if (invalidSource) v = 0xFF;
        if (m_highSpeed) exec();
        write(dst, v);
    }
    // The source, destination and length keep counting (and keep their last values)
    m_hdmaSource = (uint16_t)(m_hdmaSource + 16);
    m_hdmaDest = (uint16_t)(m_hdmaDest + 16);
    m_hdmaLength = (m_hdmaLength - 1) & 0x7F;
    if ((m_hdmaRunning && m_hdmaLength == 0x7F) || m_hdmaDest == 0) m_hdmaRunning = false;
}

